// Builds lib/pokedex-data.ts: [dexId, english, german, japanese(katakana)] for every species.
// Lets users search Japanese cards with English or German Pokémon names.
import { writeFileSync } from 'node:fs';

const CSV_URL = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv';
const LANG = { 1: 'ja', 6: 'de', 9: 'en' };

const csv = await (await fetch(CSV_URL)).text();
const byId = new Map();
for (const line of csv.split('\n').slice(1)) {
  const [id, lang, name] = line.split(',');
  if (!LANG[lang] || !name) continue;
  const row = byId.get(+id) ?? { en: '', de: '', ja: '' };
  row[LANG[lang]] = name;
  byId.set(+id, row);
}
const out = [...byId.entries()].sort((a, b) => a[0] - b[0]).map(([id, r]) => [id, r.en, r.de, r.ja]);
writeFileSync(
  new URL('../lib/pokedex-data.ts', import.meta.url),
  `// Generated by scripts/gen-pokedex.mjs from PokeAPI species names. Do not edit.\nexport const POKEDEX: [number, string, string, string][] = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${out.length} species`);
